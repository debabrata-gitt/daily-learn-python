a=int(input("Enter the First Number :"))
b=int(input("Enter the Second Number :"))
#There are six kind of comparison operators . They are "==","<",">","<=",">=","!="

#To check the one is equal to the another we use "=="
print(a==b)

#To check the one is greater than  to the another we use ">"
print(a>b)

#To check the one  is smaller than  to the another we use "<"
print(a<b)

#To check the  one is greater than equal to the another we use ">="
print(a>=b)

#To check the  one is less than equal to the another we use "<="
print(a<=b)

#To check the  one is not equal to the another we use "!="
print(a!=b)